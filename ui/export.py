"""Downloadable JSON and Markdown versions of a FinalReport."""

import streamlit as st

from backend.schemas import FinalReport
from ui.charts import average_score, score_items

JSON_NAME = "resumeiq_report.json"
MARKDOWN_NAME = "resumeiq_report.md"


def _c(text) -> str:
    """Collapse whitespace; None becomes an empty string."""
    return " ".join(str(text or "").split())


def _bullets(items) -> list[str]:
    return [f"- {_c(i)}" for i in items] or ["- None"]


def report_to_json(report: FinalReport) -> str:
    """Full report as indented JSON, using Pydantic so no field is dropped."""
    return report.model_dump_json(indent=2)


def report_to_markdown(report: FinalReport) -> str:
    """Readable Markdown report. Handles missing evaluation and job match."""
    out = ["# ResumeIQ Report", ""]
    out += ["## Executive summary", "", _c(report.executive_summary), ""]
    out += ["## Strengths", ""] + _bullets(report.strengths) + [""]
    out += ["## Weaknesses", ""] + _bullets(report.weaknesses) + [""]

    out += ["## Quality scores", ""]
    if report.evaluation is None:
        out += ["Not available for this analysis.", ""]
    else:
        scores = report.evaluation.scores
        out += [f"Average: {average_score(scores)}/10", ""]
        out += [f"- {label}: {value}/10" for label, value in score_items(scores)]
        out += [""]

    out += ["## Skills", ""]
    if report.skills.skills:
        for s in report.skills.skills:
            evidence = _c(s.evidence) or "No evidence given."
            out.append(f"- **{_c(s.skill)}** ({_c(s.category)}, {_c(s.status)}): {evidence}")
    else:
        out.append("- None identified")
    out.append("")

    out += ["## Job match", ""]
    if report.job_match is None:
        out += ["No job description was provided, so no job match was computed.", ""]
    else:
        for m in report.job_match.matches:
            evidence = _c(m.evidence) or "No evidence given."
            out.append(f"- **{_c(m.requirement)}** ({_c(m.status)}): {evidence}")
        if not report.job_match.matches:
            out.append("- No requirements extracted")
        out += ["", "### Experience to emphasize", ""]
        out += _bullets(report.job_match.experience_to_emphasize)
        out += ["", "### Skills to develop", ""]
        out += _bullets(report.job_match.skills_to_develop)
        out.append("")

    out += ["## Recommendations", ""] + _bullets(report.recommendations) + [""]
    out += ["## Next steps", ""] + _bullets(report.next_steps) + [""]

    out += ["## Bullet rewrites", ""]
    out += [
        "Checked by code: the original line must be in the resume and the improved "
        "line may not add new numbers. Other invented claims are NOT checked, so "
        "only use what is true for you.",
        "",
    ]
    if report.bullet_rewrites:
        for rw in report.bullet_rewrites:
            out += [f"- Before: {_c(rw.original)}", f"  After: {_c(rw.improved)}"]
            if _c(rw.note):
                out.append(f"  Why: {_c(rw.note)}")
    else:
        out.append("- None kept for this analysis")
    out.append("")

    if report.evaluation is not None:
        for title, findings in (
            ("Strengths in detail", report.evaluation.strengths),
            ("Areas to improve in detail", report.evaluation.improvements),
        ):
            if findings:
                out += [f"## {title}", ""]
                for f in findings:
                    line = f"- **{_c(f.area)}**: {_c(f.observation)}"
                    if _c(f.evidence):
                        line += f" (Evidence: {_c(f.evidence)})"
                    if _c(f.suggestion):
                        line += f" Suggestion: {_c(f.suggestion)}"
                    out.append(line)
                out.append("")

    out += ["---", "Generated by ResumeIQ. Scores are AI estimates and can vary between runs.", ""]
    return "\n".join(out)


def render_downloads(report: FinalReport) -> None:
    """Draw the two download buttons."""
    st.markdown("### Download")
    st.caption(
        "The files contain content from your resume. They are saved only where "
        "you choose on your own computer."
    )
    left, right = st.columns(2)
    with left:
        st.download_button(
            "Download report (Markdown)",
            data=report_to_markdown(report),
            file_name=MARKDOWN_NAME,
            mime="text/markdown",
        )
    with right:
        st.download_button(
            "Download data (JSON)",
            data=report_to_json(report),
            file_name=JSON_NAME,
            mime="application/json",
        )